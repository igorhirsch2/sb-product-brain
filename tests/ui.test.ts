import { test } from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const require=createRequire(import.meta.url)
const {JSDOM}=require('jsdom')
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'http://localhost/'})
Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,MutationObserver:dom.window.MutationObserver})
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true})
;(globalThis as any).alert=(message:string)=>{throw new Error(message)}

test('interface: erro no arquivo, filtro, 520 preços, correção BRL e seleção reversível',async()=>{
  const React=await import('react')
  const {render,screen,fireEvent,waitFor,cleanup}=await import('@testing-library/react')
  const {default:Fixture}=await import('./ui-fixture')
  render(React.createElement(Fixture))
  assert.ok(screen.getByText('Cabeçalho de preço não identificado. Confira o original.'))
  fireEvent.click(screen.getByRole('button',{name:'+ Importar arquivo'}))
  assert.match(screen.getByText(/Excel e CSV: leitura automática/).textContent||'',/PDF/)
  fireEvent.click(screen.getByRole('button',{name:'Cancelar'}))
  fireEvent.click(screen.getByRole('button',{name:'Revisar produtos'}))
  fireEvent.change(screen.getByLabelText('Buscar proposta'),{target:{value:'inexistente'}})
  assert.ok(screen.getByText(/Nenhuma proposta pronta/))
  fireEvent.change(screen.getByLabelText('Buscar proposta'),{target:{value:''}})
  fireEvent.click(screen.getByRole('button',{name:'Editar'}))
  await waitFor(()=>assert.equal((screen.getByRole('button',{name:'Salvar correções'}) as HTMLButtonElement).disabled,false))
  fireEvent.click(screen.getByLabelText('Grupo B'))
  fireEvent.click(screen.getByRole('button',{name:'Origem e preços'}))
  assert.ok(screen.getByText('520'))
  fireEvent.change(screen.getByLabelText('Preço da linha 2, Grupo A'),{target:{value:'1.234,56'}})
  fireEvent.click(screen.getByRole('button',{name:'Mostrar mais preços (100/520)'}))
  assert.ok(screen.getByRole('button',{name:'Mostrar mais preços (200/520)'}))
  fireEvent.click(screen.getByRole('button',{name:'Salvar correções'}))
  await waitFor(()=>assert.ok(!screen.queryByRole('dialog')))
  const saved=JSON.parse(screen.getByLabelText('Resultado do teste').textContent||'{}')
  assert.equal(saved.proposed_data.price_overrides['row-0'],1234.56)
  assert.deepEqual(saved.proposed_data.included_pricing_groups,['Grupo A'])
  fireEvent.click(screen.getByRole('button',{name:'Editar'}))
  await waitFor(()=>assert.equal((screen.getByRole('button',{name:'Salvar correções'}) as HTMLButtonElement).disabled,false))
  assert.equal((screen.getByLabelText('Grupo B') as HTMLInputElement).checked,false)
  fireEvent.click(screen.getByLabelText('Grupo B'))
  fireEvent.click(screen.getByRole('button',{name:'Salvar e aprovar'}))
  await waitFor(()=>assert.match(screen.getByLabelText('Resultado do teste').textContent||'',/Aprovado: Sofá de teste/))
  cleanup()
})
